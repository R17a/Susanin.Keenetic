/* Тесты учёта погибших соединений (sf_note) — правка, по которой адрес уходит
 * в VPN без прямой пробы, если несколько РАЗНЫХ соединений на одно назначение
 * потеряли SYN. classifier.c включается в TU, чтобы дотянуться до static-функций.
 * make test (хост-компилятор; в поставку не входит).
 */
#define _GNU_SOURCE
#include "classifier.c"
#include "classifier.h"

#include <stdio.h>
#include <string.h>

static int failures = 0;
#define CHECK(cond, msg) do { if (cond) printf("ok  %s\n", msg); \
    else { printf("FAIL %s\n", msg); failures++; } } while (0)

int main(void)
{
    susanin_config cfg;
    time_t t0 = 1000000;
    char fl[64];
    int i;

    config_set_defaults(&cfg);

    printf("=== дефолты ===\n");
    CHECK(cfg.synfail_quorum == 3, "quorum по умолчанию 3");
    CHECK(cfg.synfail_window == 120, "окно по умолчанию 120 с");

    printf("=== механизм выключен ===\n");
    cfg.synfail_quorum = 0;
    for (i = 0; i < 10; i++) {
        char fl[64];
        snprintf(fl, sizeof(fl), "192.168.1.50:%d", 40000 + i);
        CHECK(sf_note(&cfg, "1.2.3.4:443", fl, t0) == 0, "quorum=0 -> никогда не срабатывает");
        break;
    }
    cfg.synfail_quorum = 3;

    printf("=== накопление по разным соединениям ===\n");
    {
        char a[64], b[64], c[64];
        snprintf(a, sizeof(a), "%s", "192.168.1.50:40001");
        snprintf(b, sizeof(b), "%s", "192.168.1.50:40002");
        snprintf(c, sizeof(c), "%s", "192.168.1.50:40003");
        CHECK(sf_note(&cfg, "5.6.7.8:443", a, t0) == 0, "1 соединение -> ещё рано");
        CHECK(sf_note(&cfg, "5.6.7.8:443", b, t0) == 0, "2 соединения -> ещё рано");
        CHECK(sf_note(&cfg, "5.6.7.8:443", c, t0) == 1, "3 соединения -> quorum");
    }

    printf("=== дедуп: одно соединение не считается многократно ===\n");
    /* Это ключевой случай: залипший поток с ретрансмитами виден сканеру каждый
     * проход, и без дедуплики он сам по себе набрал бы quorum. */
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 1");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 2");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 3");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 4");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50001", t0) == 0, "второе соединение");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50002", t0) == 1,
          "третье соединение -> quorum (повторы не считались)");

    printf("=== окно: перезапуск по истечении, а не по неактивности ===\n");
    /* Прежняя пара условий (сброс по last, вердикт по first) запирала
     * механизм: при непрерывных гибелях first не сдвигался, и после первого
     * окна вердикт был 0 навсегда. Здесь проверяется, что окно действительно
     * перезапускается и quorum набирается снова. */
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41000", t0) == 0, "1-е в окне");
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41001", t0 + 119) == 0,
          "2-е в окне (119 с от первого)");
    /* now-first = 121 > win: окно истекло, счёт начинается заново */
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41002", t0 + 121) == 0,
          "за окном -> окно перезапущено, одного соединения мало");
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41003", t0 + 130) == 0,
          "2-е в новом окне");
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41004", t0 + 140) == 1,
          "3-е в новом окне -> quorum набран снова");

    printf("=== регрессия мёртвой зоны: непрерывные гибели дают quorum в каждом окне ===\n");
    {
        int fires = 0, win_seen[8] = { 0, 0, 0, 0, 0, 0, 0, 0 };
        for (i = 0; i < 40; i++) {
            time_t t = t0 + 10000 + i * 10;      /* событие каждые 10 с */
            int v;
            snprintf(fl, sizeof(fl), "192.168.1.60:%d", 44000 + i);
            v = sf_note(&cfg, "203.0.113.5:8001", fl, t);
            if (v) {
                int w = (int)((t - (t0 + 10000)) / 120);
                fires++;
                if (w >= 0 && w < 8)
                    win_seen[w] = 1;
            }
        }
        {
            int windows = 0, w;
            for (w = 0; w < 8; w++)
                if (win_seen[w])
                    windows++;
            CHECK(fires > 0 && windows >= 3,
                  "400 с непрерывных гибелей: quorum в трёх разных окнах (было: только в первом)");
            printf("     (срабатываний=%d, окон с срабатыванием=%d из ~4)\n", fires, windows);
        }
    }

    printf("=== одно залипшее соединение не даёт quorum ни в одном окне ===\n");
    {
        int fired = 0;
        for (i = 0; i < 60; i++) {
            /* то же соединение, события каждые 5 с — 300 с, то есть >2 окон */
            if (sf_note(&cfg, "203.0.113.6:443", "192.168.1.61:47000", t0 + 20000 + i * 5))
                fired++;
        }
        CHECK(fired == 0, "залипший поток с ретрансмитами за 300 с -> ни одного quorum");
    }

    printf("=== quorum выше размера кольца: только кламп, без накрутки ===\n");
    cfg.synfail_quorum = 9;              /* кольцо = 8 */
    {
        int fired_at = -1, i2;
        for (i2 = 0; i2 < 7; i2++) {
            snprintf(fl, sizeof(fl), "192.168.1.62:%d", 48000 + i2);
            if (sf_note(&cfg, "203.0.113.7:443", fl, t0 + 40000 + i2)) {
                fired_at = i2 + 1;
                break;
            }
        }
        CHECK(fired_at < 0, "7 разных соединений при quorum=9 (кламплен в 8) -> не сработало");
        snprintf(fl, sizeof(fl), "%s", "192.168.1.62:48999");
        CHECK(sf_note(&cfg, "203.0.113.7:443", fl, t0 + 40007) == 1,
              "8-е соединение -> quorum (кламп до размера кольца)");
    }
    /* Повторное появление уже вытесненных соединений не должно накручивать
     * счётчик: 7 разных соединений, гоняемых по кругу, quorum=8 не дают. */
    {
        int fired = 0, r;
        cfg.synfail_quorum = 8;
        for (r = 0; r < 30; r++) {
            int j = r % 7;
            snprintf(fl, sizeof(fl), "192.168.1.63:%d", 49000 + j);
            if (sf_note(&cfg, "203.0.113.8:443", fl, t0 + 50000 + r))
                fired++;
        }
        CHECK(fired == 0,
              "7 соединений по кругу не набирают quorum=8 (нет накрутки вытеснением)");
    }
    cfg.synfail_quorum = 3;

    printf("=== разные назначения не путаются ===\n");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42000", t0) == 0, "новое назначение");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42001", t0) == 0, "2-е");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42002", t0) == 1, "3-е -> quorum");

    printf("\n%s\n", failures ? "ЕСТЬ ОШИБКИ" : "ИТОГ: все проверки пройдены");
    return failures ? 1 : 0;
}
