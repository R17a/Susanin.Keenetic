/* Тесты улики гибели прямого пути (sf_note) — правка, по которой адрес уходит
 * в VPN без прямой пробы, если несколько РАЗНЫХ соединений на одно назначение
 * потеряли SYN. classifier.c включается в TU, чтобы дотянуться до static-функций.
 * make test (хост-компилятор; в поставку не входит).
 */
#define _GNU_SOURCE
#include "classifier.c"
#include "classifier.h"

#include <stdio.h>
#include <string.h>

static int failures = 0;
#define CHECK(cond, msg) do { if (cond) printf("ok  %s\n", msg); \
    else { printf("FAIL %s\n", msg); failures++; } } while (0)

int main(void)
{
    susanin_config cfg;
    time_t t0 = 1000000;
    int i;

    config_set_defaults(&cfg);

    printf("=== дефолты ===\n");
    CHECK(cfg.synfail_quorum == 3, "quorum по умолчанию 3");
    CHECK(cfg.synfail_window == 120, "окно по умолчанию 120 с");

    printf("=== механизм выключен ===\n");
    cfg.synfail_quorum = 0;
    for (i = 0; i < 10; i++) {
        char fl[64];
        snprintf(fl, sizeof(fl), "192.168.1.50:%d", 40000 + i);
        CHECK(sf_note(&cfg, "1.2.3.4:443", fl, t0) == 0, "quorum=0 -> никогда не срабатывает");
        break;
    }
    cfg.synfail_quorum = 3;

    printf("=== накопление по разным соединениям ===\n");
    {
        char a[64], b[64], c[64];
        snprintf(a, sizeof(a), "%s", "192.168.1.50:40001");
        snprintf(b, sizeof(b), "%s", "192.168.1.50:40002");
        snprintf(c, sizeof(c), "%s", "192.168.1.50:40003");
        CHECK(sf_note(&cfg, "5.6.7.8:443", a, t0) == 0, "1 соединение -> ещё рано");
        CHECK(sf_note(&cfg, "5.6.7.8:443", b, t0) == 0, "2 соединения -> ещё рано");
        CHECK(sf_note(&cfg, "5.6.7.8:443", c, t0) == 1, "3 соединения -> quorum");
    }

    printf("=== дедуп: одно соединение не считается многократно ===\n");
    /* Это ключевой случай: залипший поток с ретрансмитами виден сканеру каждый
     * проход, и без дедуплики он сам по себе набрал бы quorum. */
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 1");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 2");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 3");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50000", t0) == 0, "повтор 4");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50001", t0) == 0, "второе соединение");
    CHECK(sf_note(&cfg, "9.9.9.9:8001", "192.168.1.64:50002", t0) == 1,
          "третье соединение -> quorum (повторы не считались)");

    printf("=== окно протухает ===\n");
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41000", t0) == 0, "1-е в новом окне");
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41001", t0 + 119) == 0, "2-е в окне");
    /* третье — уже за пределами окна от первого: счёт начинается заново */
    CHECK(sf_note(&cfg, "8.8.8.8:443", "192.168.1.45:41002", t0 + 121) == 0,
          "за окном -> счётчик сброшен, quorum не набран");

    printf("=== разные назначения не путаются ===\n");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42000", t0) == 0, "новое назначение");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42001", t0) == 0, "2-е");
    CHECK(sf_note(&cfg, "7.7.7.7:443", "192.168.1.46:42002", t0) == 1, "3-е -> quorum");

    printf("\n%s\n", failures ? "ЕСТЬ ОШИБКИ" : "ИТОГ: все проверки пройдены");
    return failures ? 1 : 0;
}
