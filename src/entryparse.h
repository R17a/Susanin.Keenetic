#ifndef ENTRYPARSE_H
#define ENTRYPARSE_H

#include <stddef.h>

/* Разбор одной содержательной строки списка vpn_always/vpn_never.
 *
 * Форматы:
 *   domain.com            — домен, всегда через VPN
 *   ?domain.com           — МЯГКАЯ запись: по умолчанию напрямую, но если
 *                           прямой путь деградировал, агент может уйти в VPN
 *                           (ru_guard такую запись не запирает напрямую);
 *   *.domain.com          — домен и поддомены;
 *   ?*.domain.com         — мягкая зона;
 *   1.2.3.4               — адрес;
 *   1.2.3.0/24            — сеть (нормализуется по маске).
 *
 * Комментарии (#) и пустые строки сюда не попадают — их отбрасывает вызывающий
 * (или функция вернёт 0).
 *
 * Возврат: 1 — строка разобрана, 0 — невалидна.
 * out получает имя в нижнем регистре (для сети — нормализованный CIDR).
 * is_wild: имя было записано как *.domain.
 * is_net:  имя — CIDR a.b.c.d/n.
 * is_soft: строка была с префиксом '?'.
 */
int entry_parse(const char *line, char *out, size_t n,
                int *is_wild, int *is_net, int *is_soft);

#endif
